async function seedAttributes() {
  const connection = await pool.getConnection();

  try {
    console.log('🌱 Iniciando seed de atributos...');

    // Limpar atributos existentes
    await connection.query('DELETE FROM `attributeValues`');
    await connection.query('DELETE FROM `attributes`');

    // Inserir atributos
    for (const attr of attributesData) {
      const [result] = await connection.query(
        'INSERT INTO `attributes` (`name`, `slug`, `description`, `type`, `icon`, `displayOrder`, `isActive`, `createdAt`, `updatedAt`) VALUES (?, ?, ?, ?, ?, ?, ?, NOW(), NOW())',
        [
          attr.name,
          attr.slug,
          attr.category,
          attr.type,
          null,
          0,
          true,
        ]
      );

      // Inserir valor do atributo
      await connection.query(
        'INSERT INTO `attributeValues` (`attributeId`, `value`, `priceModifier`, `timeModifier`, `isActive`, `createdAt`, `updatedAt`) VALUES (?, ?, ?, ?, ?, NOW(), NOW())',
        [
          result.insertId,
          attr.name,
          attr.priceModifier,
          attr.timeModifier,
          true,
        ]
      );
    }

    console.log(`✅ ${attributesData.length} atributos inseridos com sucesso!`);
  } catch (error) {
    console.error('❌ Erro ao inserir atributos:', error);
  } finally {
    await connection.release();
    await pool.end();
  }
}

seedAttributes();
